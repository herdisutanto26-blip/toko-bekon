-- Kemasan dan harga jual kasir per satuan.
-- Satu barang katalog bisa punya lebih dari satu kemasan, misalnya sak dan kg.
-- konversi = jumlah satuan stok untuk 1 kemasan. Tidak mengubah barang, stok, atau harga jual utama.
-- Aman dijalankan ulang.

create table if not exists toko.produk_kemasan (
  id uuid primary key default gen_random_uuid(),
  produk_id uuid not null references toko.produk (id) on delete cascade,
  satuan text not null,
  harga_jual numeric not null,
  konversi numeric,
  created_at timestamptz not null default now(),
  unique (produk_id, satuan)
);

comment on table toko.produk_kemasan is
  'Harga jual kasir per kemasan. Satu barang bisa sak dan kg, masing-masing dengan harga sendiri.';
comment on column toko.produk_kemasan.konversi is
  'Berapa satuan stok untuk 1 kemasan ini. Sak semen = 1, kg semen 40 kg = 0,025. Kosong bila tidak diketahui.';

alter table toko.produk_kemasan enable row level security;
drop policy if exists produk_kemasan_all on toko.produk_kemasan;
create policy produk_kemasan_all on toko.produk_kemasan
  for all to anon, authenticated
  using (true) with check (true);
grant select, insert, update, delete on toko.produk_kemasan to anon, authenticated, service_role;

